def main():
    import argparse

    parser = argparse.ArgumentParser(description="HAKIKI-KPC Ingestion Pipeline")
    parser.add_argument(
        "--db", type=str, default="data/custody_data.db",
        help="Path to source SQLite from generate_custody_data.py"
    )
    parser.add_argument(
        "--parquet", type=str, default="data/custody_reconciled.parquet",
        help="Output Parquet path"
    )
    parser.add_argument(
        "--target_db", type=str, default="data/custody_pipeline.db",
        help="Target SQLite pipeline output path"
    )
    args = parser.parse_args()

    pipeline = CustodyIngestionPipeline(db_path=args.db)
    pipeline.run_full_pipeline(
        parquet_path=args.parquet,
        target_db=args.target_db,
    )


if __name__ == "__main__":
    main()