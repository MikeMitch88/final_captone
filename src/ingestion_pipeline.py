def validate_column_types(df: pd.DataFrame, schema: Dict[str, Any]) -> pd.DataFrame:
    """Validate and coerce column types per schema. Raises ValueError on failure."""
    for col, dtype in schema["columns"].items():
        if col not in df.columns:
            raise ValueError(f"Missing required column: {col}")
        try:
            df[col] = df[col].astype(dtype)
        except (ValueError, TypeError) as e:
            raise ValueError(f"Type coercion failed for column {col}: {e}")

    # Validate enumerated columns
    for val_col, allowed in schema.get("valid_values", {}).items():
        if val_col in df.columns:
            for idx, val in df[val_col].items():
                if val not in allowed:
                    raise ValueError(
                        f"Invalid value '{val}' in column '{val_col}' at index {idx}. "
                        f"Allowed: {allowed}"
                    )

    return df


