class CustodyIngestionPipeline:
    """Production-ready ingestion pipeline for HAKIKI-KPC custody data."""

    def __init__(self, db_path: str = "/home/mike_mitch/Desktop/EMTech/final_capstone/data/custody_data.db"):
        self.db_path = db_path
        self.conn: sqlite3.Connection | None = None
        self.dfs: Dict[str, pd.DataFrame] = {}

    def load_raw_data(self) -> None:
        """Load all tables from the source SQLite database."""
        self.conn = sqlite3.connect(self.db_path)
        tables = ["kra_manifests", "rects_telemetry", "kpc_depot_meters", "depot_lab_quality"]

        for table in tables:
            df = pd.read_sql(f"SELECT * FROM {table}", self.conn)
            # Ensure timestamp columns are parsed
            if "timestamp" in df.columns:
                df["timestamp"] = pd.to_datetime(df["timestamp"], errors="coerce")
            self.dfs[table] = df

        # Load reconciled if exists
        if "reconciled_custody_events" in pd.read_sql(
            "SELECT name FROM sqlite_master WHERE type='table'", self.conn
        ).name:
            self.dfs["reconciled_custody_events"] = pd.read_sql(
                "SELECT * FROM reconciled_custody_events", self.conn
            )

        print(f"Loaded {len(tables)} raw tables from {self.db_path}")

    def validate_and_coerce(self) -> None:
        """Validate column types and enumerated values for each DataFrame."""
        for table, schema in REQUIRED_SCHEMA.items():
            if table in self.dfs:
                self.dfs[table] = validate_column_types(self.dfs[table], schema)
                print(f"Validated: {table} ({len(self.dfs[table])} rows)")

    def engineer_reconciliation(self) -> pd.DataFrame:
        """Run the custody reconciliation & discrepancy engine.

        Returns the reconciled_custody_events DataFrame.
        """
        if "kra_manifests" not in self.dfs or "rects_telemetry" not in self.dfs or \
           "kpc_depot_meters" not in self.dfs or "depot_lab_quality" not in self.dfs:
            raise RuntimeError("Missing required DataFrames for reconciliation.")

        m = self.dfs["kra_manifests"]
        t = self.dfs["rects_telemetry"]
        d = self.dfs["kpc_depot_meters"]
        q = self.dfs["depot_lab_quality"]

        # Inner join on consignment_id
        merged = m.merge(t, on="consignment_id", how="inner", suffixes=("_m", "_t")) \
                  .merge(d, on="consignment_id", how="inner") \
                  .merge(q, on="consignment_id", how="inner")

        if merged.empty:
            raise RuntimeError("Merge produced no rows — check consignment_id consistency.")

        # --- Volumetric Shrinkage ---
        merged["volumetric_shrinkage_pct"] = compute_volumetric_shrinkage(merged)

        # --- Density Deviation ---
        merged["density_deviation_pct"] = compute_density_deviation(merged)

        # --- Anomaly Index ---
        seal_tamper = merged["e_seal_tamper_flag"].values
        geofence = merged["geofence_status"].values
        density_dev = merged["density_deviation_pct"].values

        # Encode geofence for index: OK=0, Out-of-Corridor=1, Route-Deviation=2
        geofence_enc = np.where(geofence == "Route-Deviation", 2,
                                np.where(geofence == "Out-of-Corridor", 1, 0))

        raw = 0.4 * seal_tamper + 0.4 * geofence_enc + 0.2 * (density_dev / 20.0)  # normalize approx
        anomaly_index = np.clip(raw * 100, 0, 100).round(2)

        # Handle duplicate depot_id columns (depot_meters and depot_lab_quality both have depot_id)
        depot_id_cols = [c for c in merged.columns if c.startswith("depot_id")]
        if len(depot_id_cols) > 1:
            merged = merged.rename(columns={depot_id_cols[0]: "depot_id_std", depot_id_cols[1]: "depot_id_lab"})
            merged = merged.drop(columns="depot_id_lab")
            merged = merged.rename(columns={"depot_id_std": "depot_id"})
        elif len(depot_id_cols) == 1:
            if depot_id_cols[0] != "depot_id":
                merged = merged.rename(columns={depot_id_cols[0]: "depot_id"})

        # --- Risk Flag ---
        # Re-use simple threshold logic
        quality_flag = q["pass_quality_flag"].values if hasattr(q, "values") else np.array(q["pass_quality_flag"])
        # quality_flag alignment via merge
        quality_flag = merged["pass_quality_flag"].values

        risk = assign_risk_flag(anomaly_index, seal_tamper, density_dev, quality_flag)

        # Build output
        reconciled = pd.DataFrame(
            {
                "event_id": [f"REC_{i:06d}" for i in range(len(merged))],
                "manifest_id": merged["manifest_id"].values,
                "consignment_id": merged["consignment_id"].values,
                "depot_id": merged["depot_id"].values,
                "volumetric_shrinkage_pct": merged["volumetric_shrinkage_pct"].values,
                "density_deviation_pct": merged["density_deviation_pct"].values,
                "custody_handover_anomaly_index": anomaly_index,
                "anomaly_risk_flag": risk,
                "calculated_at": datetime.now(),
            }
        )

        self.dfs["reconciled_custody_events"] = reconciled
        print(f"Reconciliation complete: {len(reconciled)} events computed.")
        return reconciled

    def output_parquet(self, parquet_path: str = "/home/mike_mitch/Desktop/EMTech/final_capstone/data/custody_reconciled.parquet") -> None:
        """Write reconciled_custody_events to Parquet format."""
        if "reconciled_custody_events" not in self.dfs:
            raise RuntimeError("No reconciled data — run engineer_reconciliation first.")
        self.dfs["reconciled_custody_events"].to_parquet(parquet_path, index=False)
        print(f"Wrote reconciled events to: {parquet_path}")

    def output_sqlite(self, db_path: str = "/home/mike_mitch/Desktop/EMTech/final_capstone/data/custody_pipeline.db") -> None:
        """Write all validated + reconciled tables to a target SQLite database."""
        # Always create a new connection to avoid conflict with source DB connection
        conn = sqlite3.connect(db_path)

        # Write all source tables
        for table, df in self.dfs.items():
            df.to_sql(table, conn, if_exists="replace", index=False)

        # Write indexes (matching schema.sql style)
        indexes = [
            "CREATE INDEX IF NOT EXISTS idx_pipe_manifests_product ON kra_manifests (product_type)",
            "CREATE INDEX IF NOT EXISTS idx_pipe_manifests_dest ON kra_manifests (destination_type)",
            "CREATE INDEX IF NOT EXISTS idx_pipe_manifests_omc ON kra_manifests (omc)",
            "CREATE INDEX IF NOT EXISTS idx_pipe_telemetry_geofence ON rects_telemetry (geofence_status)",
            "CREATE INDEX IF NOT EXISTS idx_pipe_telemetry_tamper ON rects_telemetry (e_seal_tamper_flag)",
            "CREATE INDEX IF NOT EXISTS idx_pipe_depots_meters ON kpc_depot_meters (depot_id)",
            "CREATE INDEX IF NOT EXISTS idx_pipe_lab_quality ON depot_lab_quality (depot_id)",
            "CREATE INDEX IF NOT EXISTS idx_pipeline_events_manifest ON reconciled_custody_events (manifest_id)",
            "CREATE INDEX IF NOT EXISTS idx_pipeline_events_consignment ON reconciled_custody_events (consignment_id)",
            "CREATE INDEX IF NOT EXISTS idx_pipeline_events_risk ON reconciled_custody_events (anomaly_risk_flag)",
        ]
        for stmt in indexes:
            conn.execute(stmt)

        conn.commit()
        conn.close()
        print(f"Wrote all tables to SQLite: {db_path}")
        # self.conn = None

    def run_full_pipeline(
        self,
        parquet_path: str = "/home/mike_mitch/Desktop/EMTech/final_capstone/data/custody_reconciled.parquet",
        target_db: str = "/home/mike_mitch/Desktop/EMTech/final_capstone/data/custody_pipeline.db",
    ) -> None:
        """Execute the full pipeline: load → validate → reconcile → output."""
        self.load_raw_data()
        self.validate_and_coerce()
        self.engineer_reconciliation()
        self.output_parquet(parquet_path)
        self.output_sqlite(target_db)
        print("\nPipeline execution complete.")


