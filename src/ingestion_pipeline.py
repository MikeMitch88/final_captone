# Custody Reconciliation & Discrepancy Engine
# ---------------------------------------------------------------------------

def compute_volumetric_shrinkage(df: pd.DataFrame) -> pd.Series:
    """Volumetric Shrinkage (%) = (V_manifest - V_depot_meter) / V_manifest * 100."""
    manifest_vol = df["declared_volume_litres"]
    depot_vol = df["meter_in_volume"]
    # Avoid division by zero
    with np.errstate(divide="ignore", invalid="ignore"):
        shrinkage = ((manifest_vol - depot_vol) / manifest_vol) * 100
    shrinkage = shrinkage.replace([np.inf, -np.inf], np.nan).fillna(0)
    return shrinkage.round(2)


def compute_density_deviation(df: pd.DataFrame) -> pd.Series:
    """Density Deviation (%) = |ρ_lab - ρ_declared| / ρ_declared * 100."""
    rho_lab = df["density_at_15c"]
    rho_dec = df["declared_density_kg_per_m3"]
    with np.errstate(divide="ignore", invalid="ignore"):
        dev = (np.abs(rho_lab - rho_dec) / rho_dec) * 100
    dev = dev.replace([np.inf, -np.inf], np.nan).fillna(0)
    return dev.round(2)


def compute_anomaly_index(
    seal_tamper: np.ndarray,
    geofence: np.ndarray,
    density_dev: np.ndarray,
) -> np.ndarray:
    """Custody Handover Anomaly Index combining seal tamper, route deviation, and quality variance.

    Weights: seal tamper 0.4 + geofence deviation 0.4 + density variance 0.2
    Geofence mapping: OK=0, Out-of-Corridor=1, Route-Deviation=2
    Output scaled to 0–100.
    """
    # Encode geofence
    geofence_enc = np.where(geofence == "Route-Deviation", 2,
                            np.where(geofence == "Out-of-Corridor", 1, 0)).astype(float)

    # Normalize density deviation (clamp extreme values)
    dev_norm = np.clip(density_dev / np.percentile(density_dev[density_dev > 0], 95), 0, 1)

    # Weighted composite
    raw = 0.4 * seal_tamper.astype(float) + 0.4 * geofence_enc + 0.2 * dev_norm
    # Scale to 0–100
    index = np.clip(raw * 100, 0, 100)
    return np.round(index, 2)


def assign_risk_flag(
    anomaly_index: np.ndarray,
    seal_tamper: np.ndarray,
    density_dev: np.ndarray,
    quality_flag: np.ndarray,
) -> np.ndarray:
    """Assign anomaly risk flag: Low / Medium / High."""

    # Base thresholds on anomaly index
    high_thresh = 70.0
    med_thresh = 40.0

    risk = np.where(anomaly_index >= high_thresh, "High",
                    np.where(anomaly_index >= med_thresh, "Medium", "Low"))

    # Quality failure bump: if pass_quality_flag == 0, ensure at least Medium
    quality_failure = quality_flag == 0
    risk = np.where(
        quality_failure & (risk == "Low"), "Medium", risk
    )

    # Dampen High if density normal (no density deviation)
    normal_density = density_dev < 5.0
    risk = np.where(
        normal_density & (risk == "High"), "Medium", risk
    )

    return risk


